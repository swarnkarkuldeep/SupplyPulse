log = logging.getLogger(__name__)

PII_RAW = ["Customer Fname", "Customer Lname", "Customer Street", "Customer Zipcode"]
MASKED = "REDACTED"
META_FILE = "meta.json"
TABLE_ORDER = [
    "dim_category", "dim_product", "dim_customer", "dim_geography",
    "dim_shipping_mode", "dim_date", "fact_order_items",
]  # fmt: skip


def read_raw(path: Path, encoding: str) -> pd.DataFrame:
    """Read the raw DataCo CSV with its real encoding."""
    return pd.read_csv(path, encoding=encoding)


def encoding_report(path: Path, declared: str) -> dict:
    """Test the encoding claim: does the file decode as UTF-8, and does it decode as declared?"""
    raw = Path(path).read_bytes()
    out = {"declared": declared}
    for enc in ("utf-8", declared):
        try:
            raw.decode(enc)
            out[enc] = "decodes cleanly"
        except UnicodeDecodeError as exc:
            out[enc] = f"fails at byte {exc.start}"
    return out


def profile_raw(df: pd.DataFrame) -> dict:
    """Shape, dtypes, null rates, cardinality, duplicates and date range of the raw frame."""
    cols = pd.DataFrame(
        {
            "dtype": df.dtypes.astype(str),
            "null_rate": df.isna().mean(),
            "n_unique": df.nunique(),
        }
    )
    order_ts = pd.to_datetime(df["order date (DateOrders)"], format=cl.DATE_FORMAT)
    ship_ts = pd.to_datetime(df["shipping date (DateOrders)"], format=cl.DATE_FORMAT)
    return {
        "shape": df.shape,
        "columns": cols,
        "duplicate_rows": int(df.duplicated().sum()),
        "order_range": (order_ts.min(), order_ts.max()),
        "ship_range": (ship_ts.min(), ship_ts.max()),
        "order_ts": order_ts,
        "n_orders": int(df["Order Id"].nunique()),
        "n_customers": int(df["Customer Id"].nunique()),
        "numeric": df.select_dtypes("number").describe().T,
    }


def plot_monthly_orders(order_ts: pd.Series, tail: dict, path: Path) -> Path:
    """Monthly order-item volume with the abnormal tail marked."""
    monthly = order_ts.dt.to_period("M").value_counts().sort_index()
    x = monthly.index.to_timestamp()
    fig, ax = plt.subplots()
    ax.bar(x, monthly.values, width=25, color=PALETTE["blue"])
    if tail.get("abnormal_tail"):
        start = pd.Timestamp(tail["first_abnormal_week"])
        ax.axvspan(start, x.max() + pd.Timedelta(days=30), color=PALETTE["red"], alpha=0.15)
        ax.set_ylim(0, monthly.max() * 1.15)
        ax.annotate(
            f"Abnormal tail from {start:%b %Y} (excluded from forecasting)",
            xy=(start, monthly.max() * 1.07),
            xytext=(-6, 0),
            textcoords="offset points",
            ha="right",
            color=PALETTE["red"],
        )
    ax.set_ylabel("Order items per month")
    if tail.get("abnormal_tail"):
        start = pd.Timestamp(tail["first_abnormal_week"])
        ax.set_title(f"Order volume is steady until {start:%b %Y}, then drops {tail['drop_pct']:.0%}")
    else:
        ax.set_title("Order volume is steady month to month")
    return save_fig(fig, path)


def plot_distributions(df: pd.DataFrame, path: Path) -> Path:
    """Distributions of the key numeric columns."""
    specs = [
        ("Order Item Quantity", "Units per order item", np.arange(0.5, 5.6, 1.0)),
        ("Order Item Discount Rate", "Discount rate", np.arange(-0.005, 0.26, 0.01)),
        ("Order Item Profit Ratio", "Profit ratio (profit / net sales)", 30),
        ("Sales", "Gross sales per item ($)", 40),
    ]
    fig, axes = plt.subplots(2, 2, figsize=(10, 6))
    for ax, (col, label, bins) in zip(axes.ravel(), specs, strict=True):
        ax.hist(df[col], bins=bins, color=PALETTE["blue"])
        ax.set_xlabel(label)
        ax.set_ylabel("Order items")
    single = (df["Order Item Quantity"] == 1).mean()
    losing = (df["Order Item Profit Ratio"] < 0).mean()
    fig.suptitle(
        f"{single:.0%} of items are single units, discounts reach "
        f"{df['Order Item Discount Rate'].max():.0%}, and {losing:.0%} of items lose money",
        x=0.01,
        ha="left",
        fontweight="bold",
        fontsize=11,
    )
    return save_fig(fig, path)


def profile_markdown(p: dict, enc: dict, tail: dict, figures: dict[str, str], rows_note: str = "") -> str:
    """Render reports/data_profile.md."""
    rows, cols = p["shape"]
    lines = [
        "# Raw data profile",
        "",
        "Generated by `python -m sca ingest`. Every number below was computed from the raw file.",
        "",
        rows_note,
        "## Shape and integrity",
        "",
        f"- **{rows:,} rows x {cols} columns** (one row per order item)",
        f"- {p['n_orders']:,} distinct orders, {p['n_customers']:,} distinct customers",
        f"- Fully duplicated rows: **{p['duplicate_rows']:,}**",
        f"- Order dates: {p['order_range'][0]:%Y-%m-%d} to {p['order_range'][1]:%Y-%m-%d}",
        f"- Shipping dates: {p['ship_range'][0]:%Y-%m-%d} to {p['ship_range'][1]:%Y-%m-%d}",
        f"- Encoding: UTF-8 {enc['utf-8']}; {enc['declared']} {enc[enc['declared']]}",
        "",
        "## Monthly order volume",
        "",
        f"![Monthly orders]({figures['monthly']})",
        "",
    ]
    if tail.get("abnormal_tail"):
        lines += [
            f"Weekly volume falls from a median of {tail['weekly_median_before']:,.0f} order items "
            f"(26 weeks before) to {tail['weekly_median_tail']:,.0f} from the week starting "
            f"{tail['first_abnormal_week']}, a {tail['drop_pct']:.0%} drop that never recovers "
            f"({tail['tail_weeks']} weeks). The break is abrupt and the tail is nearly constant, "
            "which is more consistent with a change in how the data was produced than with a change "
            "in demand (an inference; the data cannot prove it). "
            f"Forecasting stops at **{tail['last_normal_date']}**.",
            "",
        ]
    lines += ["## Columns: dtype, nulls, cardinality", "", "| Column | dtype | Null rate | Distinct |",
              "|---|---|---:|---:|"]  # fmt: skip
    for name, r in p["columns"].iterrows():
        lines.append(f"| {name} | {r['dtype']} | {r['null_rate']:.1%} | {int(r['n_unique']):,} |")
    lines += ["", "## Key numeric distributions", "", f"![Distributions]({figures['dist']})", ""]
    num = p["numeric"][["mean", "std", "min", "50%", "max"]]
    lines += ["| Column | Mean | Std | Min | Median | Max |", "|---|---:|---:|---:|---:|---:|"]
    for name, r in num.iterrows():
        lines.append(
            f"| {name} | {r['mean']:,.2f} | {r['std']:,.2f} | {r['min']:,.2f} | "
            f"{r['50%']:,.2f} | {r['max']:,.2f} |"
        )
    return "\n".join(lines) + "\n"


def make_sample(raw: pd.DataFrame, rows: int, strat_cols: list[str], seed: int) -> pd.DataFrame:
    """Stratified sample of whole orders (all items of a sampled order are kept).

    Strata are the raw columns in ``strat_cols`` (e.g. Market, Shipping Mode); every stratum
    contributes in proportion to its share, with at least one order. Personal name and street
    columns are redacted so the committed sample holds no personal data.
    """
    rng = np.random.default_rng(seed)
    orders = raw.drop_duplicates("Order Id")[["Order Id", *strat_cols]]
    items_per_order = raw.groupby("Order Id").size().mean()
    n_orders = int(rows / items_per_order)
    frac = n_orders / len(orders)
    picked = []
    for _, grp in orders.groupby(strat_cols):
        k = max(1, round(len(grp) * frac))
        picked.extend(rng.choice(grp["Order Id"].to_numpy(), size=min(k, len(grp)), replace=False))
    out = raw[raw["Order Id"].isin(picked)].sort_values("Order Item Id").copy()
    for col in PII_RAW:
        out[col] = MASKED
    return out.reset_index(drop=True)


def write_sample(cfg: Config, paths: RunPaths) -> Path:
    """Create data/sample/sample_orders.csv from the full raw file."""
    full = cfg.resolve(cfg.paths.raw_dir) / cfg.paths.raw_file
    raw = read_raw(full, cfg.paths.raw_encoding)
    strat = [_RAW_NAME[c] for c in cfg.sample.stratify_by]
    sample = make_sample(raw, cfg.sample.rows, strat, cfg.seed)
    paths.raw_file.parent.mkdir(parents=True, exist_ok=True)
    sample.to_csv(paths.raw_file, index=False, encoding=cfg.paths.raw_encoding)
    return paths.raw_file


_RAW_NAME = {"market": "Market", "shipping_mode": "Shipping Mode"}


def run_ingest(cfg: Config, paths: RunPaths, sample: bool = False) -> dict:
    """Profile, clean and write the processed tables plus reports. Returns key numbers."""
    paths.processed_dir.mkdir(parents=True, exist_ok=True)
    paths.reports_dir.mkdir(parents=True, exist_ok=True)
    raw = read_raw(paths.raw_file, cfg.paths.raw_encoding)
    enc = encoding_report(paths.raw_file, cfg.paths.raw_encoding)
    prof = profile_raw(raw)

    flat, clog = cl.clean_orders(raw)
    tail = cl.detect_tail_cutoff(
        flat["order_week"], cfg.forecast.tail_baseline_weeks, cfg.forecast.tail_drop_ratio
    )
    if cfg.forecast.cutoff_override:
        tail = {**tail, "last_normal_date": cfg.forecast.cutoff_override, "overridden": True}
    tables = cl.build_star_schema(flat)

    figs = {
        "monthly": plot_monthly_orders(
            prof["order_ts"], tail, paths.figures_dir / "profile_monthly_orders.png"
        ),
        "dist": plot_distributions(raw, paths.figures_dir / "profile_distributions.png"),
    }
    rel = {k: f"figures/{v.name}" for k, v in figs.items()}
    note = (
        "> **Sample run.** This profile describes `data/sample/`, not the full dataset.\n" if sample else ""
    )
    (paths.reports_dir / "data_profile.md").write_text(
        profile_markdown(prof, enc, tail, rel, note), encoding="utf-8"
    )
    (paths.reports_dir / "cleaning_log.md").write_text(cl.cleaning_log_markdown(clog, tail), encoding="utf-8")
    for name, df in tables.items():
        df.to_parquet(paths.processed_dir / f"{name}.parquet", index=False)
    meta = {
        "rows_raw": clog.rows_raw,
        "rows_clean": clog.rows_clean,
        "tail": tail,
        "sample": sample,
    }
    (paths.processed_dir / META_FILE).write_text(json.dumps(meta, indent=2), encoding="utf-8")
    log.info("ingest complete: %s -> %s rows", clog.rows_raw, clog.rows_clean)
    return meta


def read_processed(processed_dir: Path) -> dict[str, pd.DataFrame]:
    """Load the parquet tables written by run_ingest."""
    return {t: pd.read_parquet(processed_dir / f"{t}.parquet") for t in TABLE_ORDER}
